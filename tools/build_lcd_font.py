for alias, original in {
    "−": "-",
    "│": "|",
    "ᴇ": "E",
    "ℯ": "e",
    "↔": "=",
    "⇄": "=",
}.items():
    PATTERNS[alias] = PATTERNS[original]


def build():
    builder = FontBuilder(1000, isTTF=True)
    cmap = {ord(char): f"uni{ord(char):04X}" for char in PATTERNS}
    builder.setupGlyphOrder([".notdef", *cmap.values()])
    builder.setupCharacterMap(cmap)
    glyphs = {}
    for char, name in [("□", ".notdef"), *[(c, cmap[ord(c)]) for c in PATTERNS]]:
        pen = TTGlyphPen(None)
        for row, pixels in enumerate(PATTERNS[char].split("/")):
            for col, pixel in enumerate(pixels):
                if pixel == "1":
                    x, y = col * 80 + 12, (6 - row) * 80 + 160
                    pen.moveTo((x, y))
                    pen.lineTo((x, y + 65))
                    pen.lineTo((x + 65, y + 65))
                    pen.lineTo((x + 65, y))
                    pen.closePath()
        glyphs[name] = pen.glyph()
    builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics({name: (480, 12) for name in glyphs})
    builder.setupHorizontalHeader(ascent=800, descent=-200)
    builder.setupNameTable(
        {
            "familyName": "Calculator LCD",
            "styleName": "Regular",
            "uniqueFontIdentifier": "CalculatorLCD-Regular-1",
            "fullName": "Calculator LCD Regular",
            "psName": "CalculatorLCD-Regular",
            "version": "Version 1.0",
            "copyright": "Original UI font for ti36x-pro-emulator.",
        }
    )
    builder.setupOS2(
        sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200
    )
    builder.setupPost()
    builder.font.flavor = "woff2"
    output = Path(__file__).resolve().parents[1] / "ti36x/static/lcd.woff2"
    builder.save(output)
    output.chmod(0o644)


if __name__ == "__main__":
    build()
